func workbenchObjectSchema(required []string, propertyTypes map[string]interface{}) map[string]interface{} {
	properties := make(map[string]interface{}, len(propertyTypes))
	for name, value := range propertyTypes {
		propertyType, ok := value.(string)
		if !ok {
			properties[name] = value
			continue
		}
		properties[name] = map[string]interface{}{"type": propertyType}
	}
	return map[string]interface{}{
		"type":       "object",
		"properties": properties,
		"required":   required,
	}
}

